import type { Config } from './environment.schemas';

/** Renders the default TypeScript config template for the user project. */
export const renderConfigTemplate = (defaultConfig: Config): string => {
  const registryConfig = defaultConfig.registry
    ? `,
  registry: {
    url: '${defaultConfig.registry.url}',
    token: '${defaultConfig.registry.token ?? ''}',
  }`
    : `,
  // registry: {
  //   url: 'https://npm.pkg.github.com',
  //   token: process.env.PACKAGE_REGISTRY_TOKEN,
  // }`;

  return `import type { Config } from '@suitberks/contract';

// Contract configuration file, do not edit this file if you are not sure what you are doing.
// More details about Contract configuration: https://github.com/suitberks/contract#quick-start;

const contractConfig: Config = {
  app: '${defaultConfig.app}',
  contracts: ${JSON.stringify(defaultConfig.contracts)},
  emit: ${JSON.stringify(defaultConfig.emit ?? [])},
  package: {
    name: '${defaultConfig.package.name}',
    version: '${defaultConfig.package.version}',
  }${registryConfig},
};

export default contractConfig;
`;
};

